#!/usr/bin/env node
// Vendors the shared SDK fixtures into test/fixtures/ and regenerates the OpenAPI examples that
// are built from them (spec/components/examples/*.yaml).
//
//   npm run sync:fixtures -- --from /path/to/shared/fixtures   copy fixtures, then regenerate
//   npm run sync:fixtures                                       regenerate from test/fixtures/
//
// FIXTURES_DIR can be used instead of --from.
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';
import { isMain } from './lib/cli.mjs';
import {
  EXAMPLES_DIR,
  FIXTURE_EXAMPLES,
  FIXTURE_FILES,
  FIXTURES_DIR,
  fixtureExampleValue,
} from './lib/fixtures.mjs';

/** Serializes one generated example file. Strings are double-quoted so no YAML parser retypes them. */
export function renderExample(entry, value) {
  const body = YAML.stringify(
    { summary: entry.summary, description: entry.description, value },
    { lineWidth: 0, defaultStringType: 'QUOTE_DOUBLE', defaultKeyType: 'PLAIN' },
  );
  return `# Generated by scripts/sync-fixtures.mjs from test/fixtures/${entry.file}. Do not edit by hand.\n${body}`;
}

function parseSource(argv) {
  const index = argv.indexOf('--from');
  if (index !== -1) {
    const value = argv[index + 1];
    if (!value) throw new Error('--from needs a directory');
    return value;
  }
  return process.env.FIXTURES_DIR || null;
}

function main() {
  const source = parseSource(process.argv.slice(2));
  mkdirSync(FIXTURES_DIR, { recursive: true });
  if (source) {
    const from = path.resolve(source);
    for (const file of FIXTURE_FILES) {
      const src = path.join(from, file);
      if (!existsSync(src)) throw new Error(`Missing fixture ${file} in ${from}`);
      copyFileSync(src, path.join(FIXTURES_DIR, file));
    }
    console.log(`Copied ${FIXTURE_FILES.length} fixtures into test/fixtures/`);
  }
  mkdirSync(EXAMPLES_DIR, { recursive: true });
  for (const entry of FIXTURE_EXAMPLES) {
    const target = path.join(EXAMPLES_DIR, `${entry.name}.yaml`);
    writeFileSync(target, renderExample(entry, fixtureExampleValue(entry)));
  }
  console.log(`Generated ${FIXTURE_EXAMPLES.length} examples in spec/components/examples/`);
}

if (isMain(import.meta.url)) {
  main();
}
